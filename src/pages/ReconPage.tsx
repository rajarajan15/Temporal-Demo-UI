import { useMemo, useState } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import { api, ApiError, newKey } from '../api/client';
import type { ScheduleTriggerReply } from '../api/types';
import { Badge, Callout, Empty, Field, Spinner } from '../components/ui';
import { formatDateTime, shortId, timeAgo } from '../lib/format';
import { errorMessage } from '../lib/labels';
import { tracked, useTracked } from '../lib/store';
import { nightlyRunsUrl, scheduleUrl } from '../lib/temporal';
import { useTenant } from '../lib/tenant';

export function ReconPage() {
  const tenant = useTenant();
  const navigate = useNavigate();
  const all = useTracked();
  const runs = useMemo(
    () => all.filter((i) => i.tenant === tenant && i.kind === 'recon').sort((a, b) => b.createdAt - a.createdAt),
    [all, tenant],
  );

  const [pageSize, setPageSize] = useState('50');
  const [key, setKey] = useState(newKey);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<ApiError | null>(null);

  const [triggering, setTriggering] = useState(false);
  const [trigger, setTrigger] = useState<{ ok?: ScheduleTriggerReply; error?: ApiError; at: number } | null>(null);

  const size = Number(pageSize);
  const sizeOk = Number.isInteger(size) && size >= 1 && size <= 500;

  async function start(e: React.FormEvent) {
    e.preventDefault();
    if (!sizeOk) return;
    setBusy(true);
    setError(null);
    try {
      const { data } = await api.startRecon(tenant, key, size);
      tracked.upsert({ id: data.runId, tenant, kind: 'recon', lastStatus: 'RUNNING' });
      setKey(newKey());
      navigate(`/${tenant}/reconciliation/${encodeURIComponent(data.runId)}`);
    } catch (err) {
      const apiErr = err as ApiError;
      setError(apiErr);
      if (apiErr.status >= 400 && apiErr.status < 500) setKey(newKey());
    } finally {
      setBusy(false);
    }
  }

  async function triggerNightly() {
    setTriggering(true);
    try {
      const { data } = await api.triggerSchedule(tenant);
      setTrigger({ ok: data, at: Date.now() });
    } catch (err) {
      setTrigger({ error: err as ApiError, at: Date.now() });
    } finally {
      setTriggering(false);
    }
  }

  return (
    <div className="page">
      <div className="page-head">
        <div>
          <h1>Reconciliation</h1>
          <p className="page-sub">
            Compares the processor's cards with the platform's for <strong>{tenant}</strong>.
          </p>
        </div>
      </div>

      <div className="two-col">
        <form className="card" onSubmit={(e) => void start(e)} noValidate>
          <h2>Run on demand</h2>
          <p className="muted small">Runs now and shows the report here.</p>
          <Field
            label="Page size"
            htmlFor="pageSize"
            hint="Cards read from the processor per page, 1 to 500."
            error={!sizeOk ? 'Enter a whole number from 1 to 500.' : null}
          >
            <input id="pageSize" inputMode="numeric" value={pageSize} onChange={(e) => setPageSize(e.target.value)} className="input-sm" />
          </Field>
          {error && (
            <Callout tone={error.isUnavailable ? 'warning' : 'danger'} title={errorMessage(error.code)}>
              <code>{error.code}</code>
            </Callout>
          )}
          <button type="submit" className="btn btn-primary" disabled={busy || !sizeOk}>
            {busy && <Spinner />} Start reconciliation
          </button>
        </form>

        <div className="card">
          <h2>Nightly schedule</h2>
          <p className="muted small">
            Triggers the nightly run now. Its ID is generated by Temporal, so its result can only be viewed in the Temporal
            Web UI.
          </p>
          <div className="btn-row">
            <button type="button" className="btn btn-secondary" onClick={() => void triggerNightly()} disabled={triggering}>
              {triggering && <Spinner />} Trigger nightly run
            </button>
            <a className="btn btn-ghost" href={scheduleUrl(`recon-${tenant}`)} target="_blank" rel="noreferrer">
              Schedule ↗
            </a>
          </div>
          {trigger?.ok && (
            <Callout
              tone="success"
              title={`Triggered ${trigger.ok.scheduleId}`}
              actions={
                <a className="btn btn-ghost btn-sm" href={nightlyRunsUrl(tenant)} target="_blank" rel="noreferrer">
                  View runs ↗
                </a>
              }
            >
              {trigger.ok.result} at {formatDateTime(trigger.at)}
            </Callout>
          )}
          {trigger?.error && (
            <Callout tone="danger" title={errorMessage(trigger.error.code)}>
              <code>{trigger.error.code}</code>
            </Callout>
          )}
        </div>
      </div>

      <section className="card">
        <div className="card-head">
          <h2>On-demand runs</h2>
          {runs.length > 0 && (
            <button type="button" className="btn btn-ghost btn-xs" onClick={() => tracked.clear(tenant, 'recon')}>
              Clear
            </button>
          )}
        </div>
        {runs.length === 0 ? (
          <Empty title="No runs yet">Start a reconciliation to see its report.</Empty>
        ) : (
          <table className="table">
            <thead>
              <tr>
                <th>Run</th>
                <th>Status</th>
                <th className="num">Discrepancies</th>
                <th>Started</th>
              </tr>
            </thead>
            <tbody>
              {runs.map((r) => (
                <tr key={r.id}>
                  <td>
                    <Link to={`/${tenant}/reconciliation/${encodeURIComponent(r.id)}`} className="row-link">
                      <code>{shortId(r.id)}</code>
                    </Link>
                  </td>
                  <td>
                    <Badge tone={r.gone ? 'neutral' : r.lastStatus === 'COMPLETED' ? 'success' : r.lastStatus === 'FAILED' ? 'danger' : 'info'}>
                      {r.gone ? 'expired' : (r.lastStatus ?? 'unknown').toLowerCase()}
                    </Badge>
                  </td>
                  <td className="num">
                    {r.discrepancyCount === undefined ? (
                      '—'
                    ) : (
                      <span className={r.discrepancyCount ? 'text-warn' : 'text-ok'}>{r.discrepancyCount}</span>
                    )}
                  </td>
                  <td className="small muted" title={formatDateTime(r.createdAt)}>
                    {timeAgo(r.createdAt)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </section>
    </div>
  );
}
